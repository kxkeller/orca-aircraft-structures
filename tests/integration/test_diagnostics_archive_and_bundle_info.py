"""Two process-error diagnostics hazards, both additive, neither touching geometry
or a shipped structural default.

HAZARD A: ``_write_diagnostics``/``_handle_sidecar`` write the fixed filenames
``m1_report.json``/``m1_host_sections.json.gz`` on every run; overwriting them
would silently destroy the previous run's evidence. Both targets are archived
aside -- rename, never delete -- before being overwritten.

HAZARD B: a report must say which BUNDLE (``tools/build_plugin.py``'s content
hash, embedded as a header comment line in the generated bundle) produced it.
``report["bundle"]`` carries that, read from the running module's own
``__file__`` at run time.

Reuses ``M1IntegrationTestCase``'s fixture plumbing pattern from
``test_m1_capability.py`` (fresh fake orca + tmp plugin dir per test, the
checked-in GENERATED BUNDLE exec'd via ``fake_orca.exec_bundle``) rather than
importing it, since this file also needs direct access to the bundle
namespace's module-level helpers (``_archive_aside``, ``_read_bundle_info``,
etc. -- the immediate helpers of ``_write_diagnostics``).

Nothing here modifies the code under test -- it only reads it.
"""

import gzip
import json
import os
import sys
import tempfile
import time
import unittest
import unittest.mock as mock

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))

import fake_orca  # noqa: E402


FULL_CONFIG = {
    "layer_height": 0.2,
    "initial_layer_print_height": 0.2,
    "outer_wall_line_width": 0.42,
    "inner_wall_line_width": 0.42,
    "line_width": 0.42,
    "nozzle_diameter": 0.4,
    "wall_generator": "classic",
    "wall_loops": 1,
    "spiral_mode": True,
    "top_shell_layers": 0,
    "bottom_shell_layers": 0,
    "sparse_infill_density": 0,
    "enable_support": False,
    "slice_closing_radius": 0.0049,
}

# A real-shaped header, matching tools/build_plugin.py:226-238's
# ``_build_header`` verbatim (down to the blank lines separating the PEP 723
# block, the generated header, and the code below), so a positive
# ``_read_bundle_info`` test exercises the SAME scan ``_write_diagnostics``
# runs against the real checked-in bundle -- not a shape unique to the test.
_GOOD_HASH = "ab" * 32


def _bundle_text_with_header(content_hash=_GOOD_HASH):
    return (
        "# /// script\n"
        "# requires-python = \">=3.11\"\n"
        "# ///\n"
        "\n"
        "# GENERATED by tools/build_plugin.py -- do not edit; edit the sources\n"
        "# and rebuild.\n"
        "#\n"
        "# Sources (1), in dependency order: capability.py\n"
        "# Bundle content hash (sha256 of imports + module bodies below): {}\n"
        "\n"
        "from abc import ABC\n"
    ).format(content_hash)


class DiagnosticsHazardTestCase(unittest.TestCase):
    """Fixture plumbing mirroring ``test_m1_capability.py``'s
    ``M1IntegrationTestCase`` exactly (not imported, so this file can reach
    the bundle namespace's module-level helpers directly)."""

    def setUp(self):
        self._fake_orca, restore = fake_orca.install()
        self.addCleanup(restore)

        self._tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self._tmp.cleanup)
        self.plugin_dir = self._tmp.name
        self.fake_entry_file = os.path.join(self.plugin_dir, "aircraft_structures.py")

        self.namespace = fake_orca.exec_bundle(self.fake_entry_file)
        self.out_dir = os.path.join(self.plugin_dir, "m1")
        self.report_path = os.path.join(self.out_dir, "m1_report.json")
        self.sidecar_path = os.path.join(self.out_dir, "m1_host_sections.json.gz")

    def arm(self):
        with open(os.path.join(self.plugin_dir, "m1_enabled"), "w", encoding="utf-8"):
            pass

    def new_capability(self):
        cls = self.namespace["AircraftStructuresM1"]
        return cls()

    def make_object(self, n_layers=5, width_mm=20.0, depth_mm=20.0, layer_height_mm=0.2):
        return fake_orca.make_rect_object("coupon", n_layers, width_mm, depth_mm, layer_height_mm)

    def make_ctx(self, obj, config=None):
        Step = self._fake_orca.slicing.Step
        return self._fake_orca.slicing.SlicingPipelineContext(
            step=Step.posSlice,
            obj=obj,
            config=dict(FULL_CONFIG if config is None else config),
            cancelled_fn=None,
        )

    def run_success(self, cap_config=None, sidecar=False, n_layers=5):
        self.arm()
        obj = self.make_object(n_layers=n_layers)
        ctx = self.make_ctx(obj)
        cap = self.new_capability()
        cfg = {"root_solid_layers": 0, "skin_margin_mm": 1.0}
        if sidecar:
            cfg["record_host_geometry_sidecar"] = True
        if cap_config:
            cfg.update(cap_config)
        cap.get_config = lambda: json.dumps(cfg)
        result = cap.execute(ctx)
        self.assertEqual(result.status, self._fake_orca.PluginResult.Success, result.message)
        return result, cap

    def read_report(self):
        with open(self.report_path, "r", encoding="utf-8") as handle:
            return json.load(handle)

    def archive_files(self):
        if not os.path.isdir(self.out_dir):
            return []
        return sorted(
            n for n in os.listdir(self.out_dir)
            if n not in ("m1_report.json", "m1_host_sections.json.gz")
        )


# ---------------------------------------------------------------------------
# Hazard A: archive-aside on write, demonstrated across repeated runs.
# ---------------------------------------------------------------------------


class ReportArchivingAcrossRunsTests(DiagnosticsHazardTestCase):
    def test_second_run_archives_first_runs_report_and_third_archives_second(self):
        # Run 1: no prior report -> nothing to archive.
        self.run_success()
        report_1 = self.read_report()
        self.assertEqual(report_1["diagnostics_archive"]["report"]["archived"], False)
        self.assertIsNone(report_1["diagnostics_archive"]["report"]["error"])
        self.assertEqual(self.archive_files(), [])

        # Force run 1's report to a known, distinct mtime so its archive
        # name is deterministic and distinguishable from run 2's.
        t1 = time.time() - 120
        os.utime(self.report_path, (t1, t1))
        expected_stamp_1 = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(t1))

        # Run 2: archives run 1's report aside; writes its own fresh one.
        self.run_success()
        archived_after_run_2 = self.archive_files()
        self.assertEqual(
            archived_after_run_2, ["m1_report.{}.json".format(expected_stamp_1)]
        )
        report_2 = self.read_report()
        self.assertTrue(report_2["diagnostics_archive"]["report"]["archived"])
        self.assertEqual(
            os.path.basename(report_2["diagnostics_archive"]["report"]["archived_path"]),
            "m1_report.{}.json".format(expected_stamp_1),
        )
        self.assertIsNone(report_2["diagnostics_archive"]["report"]["error"])

        # Force run 2's report to a second, later, distinct mtime.
        t2 = time.time() - 60
        os.utime(self.report_path, (t2, t2))
        expected_stamp_2 = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(t2))
        self.assertNotEqual(expected_stamp_1, expected_stamp_2)

        # Run 3: archives run 2's report aside too. Run 1's archive from the
        # previous step MUST still be present -- no deletion, ever.
        self.run_success()
        archived_after_run_3 = self.archive_files()
        self.assertEqual(
            archived_after_run_3,
            sorted([
                "m1_report.{}.json".format(expected_stamp_1),
                "m1_report.{}.json".format(expected_stamp_2),
            ]),
        )
        report_3 = self.read_report()
        self.assertEqual(
            os.path.basename(report_3["diagnostics_archive"]["report"]["archived_path"]),
            "m1_report.{}.json".format(expected_stamp_2),
        )

        # Growth is visible: archive_dir file_count/total_bytes reflect both
        # archived reports still sitting on disk after run 3.
        archive_dir_stats = report_3["diagnostics_archive"]["archive_dir"]
        self.assertEqual(archive_dir_stats["file_count"], 2)
        self.assertGreater(archive_dir_stats["total_bytes"], 0)
        self.assertIsNone(archive_dir_stats["error"])

    def test_archive_collision_within_the_same_second_gets_a_suffix_not_overwritten(self):
        # Two runs with the SAME (forced) mtime on the outgoing report must
        # not collide on one archive name -- the second gets a "-1" suffix,
        # and BOTH archived files survive (no silent overwrite).
        self.run_success()
        same_t = time.time() - 10
        os.utime(self.report_path, (same_t, same_t))
        stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(same_t))

        self.run_success()
        os.utime(self.report_path, (same_t, same_t))

        self.run_success()
        files = self.archive_files()
        self.assertEqual(
            files,
            sorted([
                "m1_report.{}.json".format(stamp),
                "m1_report.{}-1.json".format(stamp),
            ]),
        )


class SidecarArchivingTests(DiagnosticsHazardTestCase):
    def test_sidecar_archived_aside_on_second_enabled_run(self):
        self.run_success(sidecar=True)
        self.assertTrue(os.path.exists(self.sidecar_path))
        t1 = time.time() - 90
        os.utime(self.sidecar_path, (t1, t1))
        expected_stamp = time.strftime("%Y%m%dT%H%M%SZ", time.gmtime(t1))

        self.run_success(sidecar=True)
        report = self.read_report()
        archived = report["host_sections_sidecar"]["archived_previous"]
        self.assertTrue(archived["archived"])
        self.assertIsNone(archived["error"])
        self.assertEqual(
            os.path.basename(archived["archived_path"]),
            "m1_host_sections.{}.json.gz".format(expected_stamp),
        )
        self.assertIn(
            "m1_host_sections.{}.json.gz".format(expected_stamp), self.archive_files()
        )
        # The canonical sidecar filename still holds THIS run's own data,
        # per the design's "canonical filenames remain the current run's
        # output" requirement.
        self.assertTrue(os.path.exists(self.sidecar_path))

    def test_sidecar_archived_previous_default_when_nothing_to_archive(self):
        self.run_success(sidecar=True)
        report = self.read_report()
        archived = report["host_sections_sidecar"]["archived_previous"]
        self.assertFalse(archived["archived"])
        self.assertIsNone(archived["archived_path"])
        self.assertIsNone(archived["error"])


