class ArchiveHelperUnitTests(DiagnosticsHazardTestCase):
    def test_archive_aside_no_existing_file_is_a_no_op(self):
        archive_aside = self.namespace["_archive_aside"]
        missing = os.path.join(self.plugin_dir, "does_not_exist.json")
        info = archive_aside(missing)
        self.assertFalse(info["archived"])
        self.assertIsNone(info["archived_path"])
        self.assertIsNone(info["error"])

    def test_archive_directory_stats_ignores_canonical_files(self):
        stats_fn = self.namespace["_archive_directory_stats"]
        os.makedirs(self.out_dir, exist_ok=True)
        with open(self.report_path, "w", encoding="utf-8") as handle:
            handle.write("{}")
        with gzip.open(self.sidecar_path, "wb") as handle:
            handle.write(b"{}")
        stats = stats_fn(self.out_dir)
        self.assertEqual(stats["file_count"], 0)
        self.assertEqual(stats["total_bytes"], 0)

    def test_archive_directory_stats_unreadable_dir_reports_error_not_raise(self):
        stats_fn = self.namespace["_archive_directory_stats"]
        stats = stats_fn(os.path.join(self.plugin_dir, "no_such_dir"))
        self.assertIsNotNone(stats["error"])
        self.assertEqual(stats["file_count"], 0)


