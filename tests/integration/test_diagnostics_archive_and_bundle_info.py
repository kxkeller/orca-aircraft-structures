class BundleContentHashReportingTests(DiagnosticsHazardTestCase):
    def test_missing_bundle_file_on_disk_is_read_false_with_error(self):
        # exec_bundle never materializes ``fake_entry_file`` on disk (it
        # execs the source text directly) -- the natural default this suite
        # otherwise runs under, and itself a valid failure path: __file__
        # names a path nothing has written.
        self.assertFalse(os.path.exists(self.fake_entry_file))
        _result, _cap = self.run_success()
        report = self.read_report()
        bundle_info = report["bundle"]
        self.assertFalse(bundle_info["read"])
        self.assertIsNone(bundle_info["content_hash"])
        self.assertIsNotNone(bundle_info["error"])

    def test_header_present_on_disk_is_read_true_with_matching_hash(self):
        with open(self.fake_entry_file, "w", encoding="utf-8") as handle:
            handle.write(_bundle_text_with_header(_GOOD_HASH))
        _result, _cap = self.run_success()
        report = self.read_report()
        bundle_info = report["bundle"]
        self.assertTrue(bundle_info["read"])
        self.assertIsNone(bundle_info["error"])
        self.assertEqual(bundle_info["content_hash"], _GOOD_HASH)

    def test_malformed_hash_line_is_read_false_with_error(self):
        with open(self.fake_entry_file, "w", encoding="utf-8") as handle:
            handle.write(_bundle_text_with_header("not-a-valid-hash"))
        _result, _cap = self.run_success()
        report = self.read_report()
        bundle_info = report["bundle"]
        self.assertFalse(bundle_info["read"])
        self.assertIsNone(bundle_info["content_hash"])
        self.assertIn("malformed hash line", bundle_info["error"])

    def test_no_header_line_at_all_is_read_false_with_error(self):
        with open(self.fake_entry_file, "w", encoding="utf-8") as handle:
            handle.write(
                "# /// script\n# ///\n\n"
                "# GENERATED by tools/build_plugin.py -- do not edit\n"
                "\nfrom abc import ABC\n"
            )
        _result, _cap = self.run_success()
        report = self.read_report()
        bundle_info = report["bundle"]
        self.assertFalse(bundle_info["read"])
        self.assertIsNone(bundle_info["content_hash"])
        self.assertEqual(
            bundle_info["error"], "no bundle content-hash header line found"
        )

    def test_unreadable_file_is_read_false_with_error(self):
        with open(self.fake_entry_file, "w", encoding="utf-8") as handle:
            handle.write(_bundle_text_with_header(_GOOD_HASH))
        real_open = open

        def _flaky_open(path, *args, **kwargs):
            if os.path.abspath(path) == os.path.abspath(self.fake_entry_file):
                raise OSError("simulated read failure")
            return real_open(path, *args, **kwargs)

        with mock.patch("builtins.open", side_effect=_flaky_open):
            _result, _cap = self.run_success()
        report = self.read_report()
        bundle_info = report["bundle"]
        self.assertFalse(bundle_info["read"])
        self.assertIn("simulated read failure", bundle_info["error"])


