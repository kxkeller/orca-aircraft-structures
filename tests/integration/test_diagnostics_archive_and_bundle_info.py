class ArchivingFailureIsNonFatalTests(DiagnosticsHazardTestCase):
    def test_rename_failure_is_recorded_but_run_still_succeeds_and_report_still_written(self):
        self.run_success()  # produces an m1_report.json to try to archive next run

        with mock.patch("os.rename", side_effect=OSError("permission denied")):
            result, _cap = self.run_success()

        self.assertEqual(result.status, self._fake_orca.PluginResult.Success)
        report = self.read_report()
        archived = report["diagnostics_archive"]["report"]
        self.assertFalse(archived["archived"])
        self.assertIsNotNone(archived["error"])
        self.assertIn("permission denied", archived["error"])

    def test_sidecar_rename_failure_is_recorded_and_sidecar_still_written(self):
        self.run_success(sidecar=True)

        real_rename = os.rename

        def _flaky_rename(src, dst):
            if src.endswith(".json.gz"):
                raise OSError("permission denied")
            return real_rename(src, dst)

        with mock.patch("os.rename", side_effect=_flaky_rename):
            result, _cap = self.run_success(sidecar=True)

        self.assertEqual(result.status, self._fake_orca.PluginResult.Success)
        report = self.read_report()
        info = report["host_sections_sidecar"]
        self.assertTrue(info["written"])  # the write itself still succeeds
        self.assertFalse(info["archived_previous"]["archived"])
        self.assertIn("permission denied", info["archived_previous"]["error"])


